// Deterministic pseudo-random generator for reproducible seasonal snow curves
function seededRand(seed: number): () => number {
  let s = seed % 2147483647;
  if (s <= 0) s += 2147483646;
  return () => {
    s = (s * 16807) % 2147483647;
    return (s - 1) / 2147483646;
  };
}

function generateSampleSnow(): SnowRecord[] {
  const records: SnowRecord[] = [];
  const seasons = [
    { yearStart: 2024, seasonId: 2025, factor: 0.94 },
    { yearStart: 2025, seasonId: 2026, factor: 1.08 },
  ];

  // Key stations with realistic weather station curves
  const snowStations = SAMPLE_STATIONS.slice(0, 26);

  snowStations.forEach((st, stIdx) => {
    const obsAlt = st.obs_alt ?? st.high_alt ?? 1850;
    const altBoost = Math.max(0.55, (obsAlt - 1200) / 1100);

    seasons.forEach(({ yearStart, seasonId, factor }) => {
      const rand = seededRand((stIdx + 1) * 1009 + seasonId * 37);
      const startDate = new Date(Date.UTC(yearStart, 10, 25)); // Nov 25
      const endDate = new Date(Date.UTC(yearStart + 1, 3, 25)); // Apr 25
      let ground = Math.round(18 * altBoost * factor);
      let maxSeen = ground;

      for (
        let d = new Date(startDate);
        d <= endDate;
        d = new Date(d.getTime() + 86400000)
      ) {
        const iso = d.toISOString().slice(0, 10);
        const dayIndex = Math.round((d.getTime() - startDate.getTime()) / 86400000);
        const progress = dayIndex / 151; // 0..1 from late Nov to late Apr

        // Peak snow accumulation around late Feb / mid March (progress ~ 0.65)
        const stormProb = progress < 0.72 ? 0.24 : 0.12;
        const isStorm = rand() < stormProb;
        const fresh = isStorm
          ? Math.round((4 + rand() * 26) * altBoost * factor)
          : 0;

        // Natural settling + spring melt after mid-March
        const settle = ground > 10 ? Math.round(ground * 0.014) : 0;
        const springMelt =
          progress > 0.72 ? Math.round((progress - 0.72) * 16 * (1.25 - altBoost * 0.4)) : 0;

        ground = Math.max(0, ground + fresh - settle - springMelt);
        if (ground > maxSeen) maxSeen = ground;

        records.push({
          station: st.name,
          day: iso,
          season: seasonId,
          ground,
          max_depth: maxSeen,
          fresh,
          obs_alt: obsAlt,
        });
      }
    });
  });

  return records;
}

export const SAMPLE_SNOW: SnowRecord[] = generateSampleSnow();
